"""The stroke alphabet used by application plates and office icons.

Many icons in a desktop theme stand for a program whose own logo is not part of
the theme: a spreadsheet, a word processor, a generic "unknown application".
Real icon themes solve this with a plate and a letter, and that is what this
module provides. Letters are tables of unit space segments rather than filled
outlines because a table is trivial to correct by eye, and because the stroke
thickness then stays even at every icon size.

Each character is registered as its own glyph (``letter-a`` .. ``letter-z``,
``digit-0`` .. ``digit-9``) so the catalogue can refer to them by name, and
``letter_shapes`` is the helper an application plate calls when it wants the
same character drawn inside a smaller box.
"""

