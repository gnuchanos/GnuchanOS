LETTER_BOX = (18.0, 18.0, 64.0, 64.0)
LETTER_THICKNESS = 8.0


def letter_shapes(
    character: str,
    fill: str,
    box: tuple[float, float, float, float] = LETTER_BOX,
    thickness: float = LETTER_THICKNESS,
) -> ShapeList:
    """Draw ``character`` as strokes inside ``box``.

    Unknown characters come back as an empty list rather than raising: an
    application tile that asks for a letter the alphabet does not carry should
    fall back to its pictogram, not stop the build.
    """
    segments = LETTER_SEGMENTS.get(character.lower())
    if segments is None:
        return []
    return strokes(segments, fill, thickness, box)


def _register_letters() -> None:
    """Expose every character as its own glyph name."""

    def make(segments: Segments, thickness: float):
        def render(tint: str) -> ShapeList:
            return strokes(segments, tint, thickness, (16.0, 16.0, 68.0, 68.0))

        return render

    for character, segments in LETTER_SEGMENTS.items():
        prefix = "digit" if character.isdigit() else "letter"
        name = f"{prefix}-{character}"
        if name in GLYPHS:
            raise ValueError(f"glyph already defined: {name}")
        GLYPHS[name] = make(segments, 9.0 if character.isdigit() else 8.0)


_register_letters()


def characters() -> Sequence[str]:
    """The characters the alphabet carries, in a stable order."""
    return tuple(LETTER_SEGMENTS)
